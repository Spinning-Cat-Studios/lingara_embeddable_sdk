use core_embed::{Command, CommandOutcome, EmbedConfig, EmbedError, EmbedEvent, EmbedStatus};
use schemars::JsonSchema;
use schemars::generate::{SchemaGenerator, SchemaSettings};
use serde_json::{Map, Value, json};

use crate::tests::header_tests::{bless, crate_dir};

fn root<T: JsonSchema>(generator: &mut SchemaGenerator, roots: &mut Map<String, Value>) {
    let schema = generator.subschema_for::<T>();
    roots.insert(T::schema_name().into_owned(), schema.to_value());
}

/// `schemars` over K1's six message types: each a `$ref` under `messages`,
/// every definition under `$defs`. Bindings read their coverage list here.
fn generate() -> String {
    let mut generator = SchemaSettings::draft2020_12().into_generator();
    let mut roots = Map::new();
    root::<Command>(&mut generator, &mut roots);
    root::<CommandOutcome>(&mut generator, &mut roots);
    root::<EmbedEvent>(&mut generator, &mut roots);
    root::<EmbedConfig>(&mut generator, &mut roots);
    root::<EmbedStatus>(&mut generator, &mut roots);
    root::<EmbedError>(&mut generator, &mut roots);
    let document = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "lingara-embed messages",
        "description": "The JSON lingara_embed.h moves (ADR 1.10.26aa D2): K1's own types, generated by `make ffi-schema`. Do not edit.",
        "messages": roots,
        "$defs": generator.take_definitions(true),
    });
    serde_json::to_string_pretty(&sorted(document)).expect("a schema serialises") + "\n"
}

/// Every object's keys in sorted order. A workspace-wide build unifies
/// serde_json's `preserve_order` on, a crate-alone build does not, and the
/// committed bytes must be the same under both.
fn sorted(value: Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut entries: Vec<(String, Value)> = map.into_iter().collect();
            entries.sort_by(|a, b| a.0.cmp(&b.0));
            Value::Object(entries.into_iter().map(|(k, v)| (k, sorted(v))).collect())
        }
        Value::Array(items) => Value::Array(items.into_iter().map(sorted).collect()),
        other => other,
    }
}

/// Every `type` tag of a tagged enum's definition.
fn tags(schema: &Value, name: &str) -> Vec<String> {
    let variants = schema["$defs"][name]["oneOf"].as_array().cloned().unwrap_or_default();
    variants.iter().filter_map(|v| v["properties"]["type"]["const"].as_str().map(str::to_owned)).collect()
}

// 1.10.26aa AC11
#[test]
fn the_committed_schema_is_the_cores_message_set() {
    let path = crate_dir().join("schema/messages.schema.json");
    let fresh = generate();
    if bless() {
        std::fs::write(&path, &fresh).expect("write the schema");
    }
    let committed = std::fs::read_to_string(&path).expect("schema/messages.schema.json is committed");
    assert!(committed == fresh, "schema/messages.schema.json is stale: run `make ffi-schema`");

    let schema: Value = serde_json::from_str(&fresh).unwrap();
    let vector: Value = serde_json::from_str(include_str!("../../../conformance/vectors/json-shape.json")).unwrap();
    for name in ["Command", "EmbedEvent", "CommandOutcome"] {
        let shaped: Vec<String> = vector["tagged"][name].as_array().unwrap().iter().map(|e| e["type"].as_str().unwrap().to_owned()).collect();
        assert_eq!(tags(&schema, name), shaped, "the schema's {name} tags are json-shape.json's, in order");
    }
}
